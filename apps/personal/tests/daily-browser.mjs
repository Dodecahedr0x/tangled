import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const repo = fileURLToPath(new URL('../../../', import.meta.url));
const folder = await fs.mkdtemp(path.join(os.tmpdir(), 'personal-daily-browser-'));
const service = spawn(process.env.TANGLED_PERSONAL_APP || path.join(repo, 'target/debug/tangled-personal'), ['serve', '--data', path.join(folder, 'library'), '--listen', '127.0.0.1:0', '--no-open']);
let browser;
try {
  const launch = await new Promise((resolve, reject) => {
    let output = '';
    const timer = setTimeout(() => reject(new Error('Personal did not launch')), 20000);
    service.once('error', reject);
    service.stdout.on('data', chunk => { output += chunk; const line = output.split('\n').find(line => /^http:\/\/127\.0\.0\.1:\d+\/#session=[a-f0-9]{64}$/.test(line)); if (line) { clearTimeout(timer); resolve(line); } });
  });
  const base = new URL(launch), token = new URLSearchParams(base.hash.slice(1)).get('session');
  const api = async (feature, input) => { const response = await fetch(`${base.origin}/api/v1/personal/${feature}`, { method: 'POST', headers: { 'x-tangled-session': token, 'content-type': 'application/json' }, body: JSON.stringify(input) }); const value = await response.json(); assert.equal(response.ok, true, value.error); return value; };
  const note = await api('notes', { action: 'create', rkey: 'daily', body: { title: 'Garden follow-up', text: 'Check the young willows.', state: 'inbox', reminderAt: Math.floor(Date.now()/1000)-60, 'vendor.example': { keep: true } } });
  const otherNote = await api('notes', { action: 'create', rkey: 'evening', body: { title: 'Evening sketch', text: 'A second note to return to.', state: 'note' } });
  const external = await api('records', { action: 'put', collection: 'pub.example.fieldNotes', rkey: 'river', body: { title: 'Third-party river record', text: 'Preserved native survey.', 'vendor.example': { untouched: true } } });
  await api('capture', { action: 'save', kind: 'text', title: 'Offline sketch', text: 'A quiet place to sketch.' });
  await api('feeds', { action: 'subscribe', url: 'https://example.test/daily.xml', title: 'Daily journal' });
  await api('feeds', { action: 'ingest', url: 'https://example.test/daily.xml', xml: '<rss version="2.0"><channel><item><guid>morning</guid><title>Morning journal</title><description>Sunlight on the river.</description></item></channel></rss>' });
  browser = await chromium.launch();
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read','clipboard-write'] });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const settled = () => page.waitForFunction(() => !document.querySelector('[aria-busy="true"]'));
  const go = async name => { await page.getByRole('link', { name, exact: true }).click(); await page.getByRole('heading', { name, level: 1, exact: true }).waitFor(); await page.waitForLoadState('networkidle'); };
  const click = async name => { await page.getByRole('button', { name, exact: true }).click(); await settled(); };
  const withDialog = async (action, accept = false) => {
    const pending = page.waitForEvent('dialog');
    const acting = action();
    const dialog = await pending;
    await (accept ? dialog.accept() : dialog.dismiss());
    await acting;
  };
  let failQueue = true;
  await page.route('**/api/v1/personal/feeds', async route => {
    if (failQueue && route.request().postDataJSON().action === 'queue') { failQueue = false; await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Temporary reading failure' }) }); }
    else await route.continue();
  });
  await page.goto(launch);
  await page.getByRole('heading', { name: 'Today', level: 1, exact: true }).waitFor({ timeout: 10000 });
  await click('Retry unread feed articles');
  await page.unroute('**/api/v1/personal/feeds');
  const due = page.getByRole('region', { name: 'Due reminders', exact: true });
  await due.getByRole('button', { name: 'Clear reminder', exact: true }).click();
  await page.waitForFunction(() => document.activeElement?.textContent === 'Undo clear reminder');
  await click('Undo clear reminder');
  assert.equal((await api('notes', { action: 'get', rkey: 'daily' })).body.reminderAt, note.body.reminderAt);
  const inbox = page.getByRole('region', { name: 'Self inbox', exact: true });
  await inbox.getByRole('button', { name: 'File to Notes', exact: true }).click();
  await click('Undo file to Notes');
  assert.equal((await api('notes', { action: 'get', rkey: 'daily' })).body.state, 'inbox');
  await page.getByRole('region', { name: 'Unread saved items', exact: true }).getByRole('button', { name: 'Mark read', exact: true }).click();
  await click('Undo mark saved item read');
  assert.equal((await api('capture', { action: 'list', read: false })).length, 1);
  await page.getByRole('region', { name: 'Unread feed articles', exact: true }).getByRole('button', { name: 'Mark read', exact: true }).click();
  await click('Undo mark feed article read');
  assert.equal((await api('feeds', { action: 'queue', unread: true })).items.length, 1);
  await due.getByRole('button', { name: 'Garden follow-up', exact: true }).click();
  await page.getByLabel('Text', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('Text', { exact: true }).inputValue(), 'Check the young willows.');
  await page.getByLabel('Text', { exact: true }).fill('Unsaved garden edits.');
  await withDialog(() => page.evaluate(() => { location.hash = 'session=' + '0'.repeat(64); }));
  assert.equal(await page.getByLabel('Text', { exact: true }).inputValue(), 'Unsaved garden edits.');
  assert.doesNotMatch(await page.evaluate(() => location.hash), /session=/);
  await withDialog(() => page.getByRole('link', { name: 'Capture', exact: true }).click());
  await page.getByRole('heading', { name: 'Notes', level: 1, exact: true }).waitFor();
  assert.equal(await page.getByLabel('Text', { exact: true }).inputValue(), 'Unsaved garden edits.');
  await withDialog(() => click('New note'));
  assert.equal(await page.getByLabel('Text', { exact: true }).inputValue(), 'Unsaved garden edits.');
  let failSave = true;
  await page.route('**/api/v1/personal/notes', async route => {
    if (failSave && route.request().postDataJSON().action === 'edit') { failSave = false; await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Temporary save failure' }) }); }
    else await route.continue();
  });
  await click('Save note');
  await page.getByRole('alert').filter({ hasText: 'Temporary save failure' }).waitFor();
  await withDialog(() => page.getByRole('link', { name: 'Capture', exact: true }).click());
  assert.equal(await page.getByLabel('Text', { exact: true }).inputValue(), 'Unsaved garden edits.');
  await page.unroute('**/api/v1/personal/notes');
  await click('Save note'); await go('Today');
  const saved = await api('notes', { action: 'get', rkey: 'daily' }); assert.equal(saved.body.text, 'Unsaved garden edits.'); assert.equal(saved.body['vendor.example'].keep, true);
  await page.goto(`${base.origin}/#notes?item=${encodeURIComponent(note.uri)}`);
  await page.getByRole('button', { name: 'Save note', exact: true }).waitFor();
  await click('Copy link');
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  assert.equal(new URL(copied).hash, `#notes?item=${encodeURIComponent(note.uri)}`); assert.doesNotMatch(copied, /session=/);
  const peer = await context.newPage(); await peer.goto(copied); await peer.getByRole('button', { name: 'Save note', exact: true }).waitFor(); await peer.close();
  const coldContext = await browser.newContext();
  const cold = await coldContext.newPage(); await cold.goto(copied);
  await cold.getByRole('heading', { name: 'Open your library’s launch link', exact: true }).waitFor();
  await cold.goto(launch); await cold.getByRole('button', { name: 'Save note', exact: true }).waitFor();
  assert.equal(await cold.getByLabel('Text', { exact: true }).inputValue(), 'Unsaved garden edits.');
  await coldContext.close();
  await page.reload(); await page.getByRole('button', { name: 'Save note', exact: true }).waitFor();
  await click('Evening sketch');
  assert.equal(await page.evaluate(() => location.hash), '#notes?item=' + encodeURIComponent(otherNote.uri));
  await page.reload(); await page.getByRole('button', { name: 'Save note', exact: true }).waitFor();
  assert.equal(await page.getByLabel('Text', { exact: true }).inputValue(), 'A second note to return to.');
  await page.goto(copied); await page.getByRole('button', { name: 'Save note', exact: true }).waitFor();
  await page.getByLabel('Text', { exact: true }).fill('Discard this edit.');
  await withDialog(() => page.close({ runBeforeUnload: true }));
  assert.equal(page.isClosed(), false);
  await withDialog(() => go('Capture'), true);
  assert.equal((await api('notes', { action: 'get', rkey: 'daily' })).body.text, 'Unsaved garden edits.');
  await page.goto(`${base.origin}/#library?item=${encodeURIComponent(external.uri)}`);
  await page.getByText('Preserved native survey.', { exact: true }).waitFor();
  await page.reload(); await page.getByText('Preserved native survey.', { exact: true }).waitFor();
  await page.goto(`${base.origin}/#notes?item=${encodeURIComponent(external.uri)}`);
  await page.getByRole('heading', { name: 'Notes', level: 1, exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Could not open this note', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Save note', exact: true }).count(), 0);
  const feed = (await api('feeds', { action: 'queue', unread: true })).items[0];
  await api('feeds', { action: 'mark', item: feed.uri, read: true });
  await page.goto(`${base.origin}/#feeds?item=${encodeURIComponent(feed.uri)}`);
  await page.getByRole('article', { name: 'Feed reader' }).getByText('Sunlight on the river.', { exact: true }).waitFor();
  await page.reload();
  await page.getByRole('article', { name: 'Feed reader' }).getByText('Sunlight on the river.', { exact: true }).waitFor();
  assert.equal((await api('feeds', { action: 'queue', unread: true })).items.length, 0);
  await api('feeds', { action: 'mark', item: feed.uri, read: false });
  await go('Today');
  if (process.env.TANGLED_UI_SCREENSHOTS) {
    await fs.mkdir(process.env.TANGLED_UI_SCREENSHOTS, { recursive: true });
    await page.screenshot({ path: path.join(process.env.TANGLED_UI_SCREENSHOTS, 'daily-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
    await page.screenshot({ path: path.join(process.env.TANGLED_UI_SCREENSHOTS, 'daily-mobile.png'), fullPage: true });
  }
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ today: true, unsavedChanges: 'cancel/save/discard', recordLinks: 'copy/reload/peer/third-party', extensionsPreserved: true, javascriptErrors: 0 }));
} finally {
  await browser?.close(); service.kill('SIGTERM');
  await new Promise(resolve => service.exitCode !== null ? resolve() : service.once('exit', resolve));
  await fs.rm(folder, { recursive: true, force: true });
}
